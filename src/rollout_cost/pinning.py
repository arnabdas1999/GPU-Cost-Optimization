"""Write the pinned configs for a GPU session (used by scripts/lightning-setup.sh).

Generates, next to configs/lightning.yaml:

* lightning.pinned.yaml - resolved model revision, vLLM binary, CPU split, price
* smoke.pinned.yaml     - one attempt per task, one at a time
* sweep.pinned.yaml     - the dev admission sweep on the pinned base

``rehearsal=True`` swaps vLLM for the mock server so the whole session can be
rehearsed on a CPU-only Linux box with the same files.
"""

from __future__ import annotations

from pathlib import Path

import yaml

from .config import ConfigError, load_raw

MOCK_ARGS = {"host": "127.0.0.1", "port": 8000, "served-model-name": "coding-model", "max-model-len": 8192,
             "max-num-seqs": 8, "policy": "mixed", "base-latency": 0.15, "per-token-latency": 0.0005,
             "enable-prefix-caching": True}


def split_cpus(available: list[int]) -> tuple[list[int], list[int]]:
    """Reserve the first half (at least 2) for vLLM and the runner; up to 4 of the rest become tool workers.

    With fewer than 4 CPUs nothing is pinned: the split would starve one side.
    """
    cpus = sorted(available)
    if len(cpus) < 4:
        return [], []
    reserved = cpus[: max(2, len(cpus) // 2)]
    workers = cpus[len(reserved):][:4]
    return reserved, workers


def _range(cpus: list[int]) -> str:
    return ",".join(str(c) for c in cpus)


def pinned_configs(configs_dir: Path, revision: str, vllm_bin: str, cpus: list[int], rate: float | None,
                   rate_source: str | None, executor: str = "local", rehearsal: bool = False,
                   model_repo: str | None = None) -> dict[str, dict]:
    base_raw = load_raw(configs_dir / "lightning.yaml")
    reserved, workers = split_cpus(cpus)
    prefix = ["taskset", "-c", _range(reserved)] if reserved else []
    if rehearsal:
        command = [*prefix, "python", "-m", "rollout_cost.mock_server", "{args}"]
        # Null out every vLLM argument inherited from the base, then use the mock's.
        args = {key: None for key in base_raw.get("server", {}).get("args", {})} | MOCK_ARGS
        model = {"revision": "rehearsal", "tokenizer_revision": "rehearsal", "repository": "mock/coding-model"}
    else:
        repository = model_repo if model_repo is not None else base_raw["model"]["repository"]
        if not isinstance(repository, str) or not repository.strip():
            raise ConfigError("model repository must be a non-empty string")
        command = [*prefix, vllm_bin, "serve", repository, "{args}"]
        args = {"revision": revision, "tokenizer-revision": revision}
        model = {"repository": repository, "revision": revision, "tokenizer_revision": revision}
    lightning = {
        "extends": "lightning.yaml",
        "name": "lightning-rehearsal" if rehearsal else "lightning",
        "model": model,
        "server": {"start_command": command, "args": args, "reserved_cpus": reserved},
        "tools": {"executor": executor, "worker_cpus": workers},
        "cost": {"allocation_hourly_rate": rate, "rate_source": rate_source},
    }
    smoke = {"extends": "lightning.pinned.yaml", "name": "smoke", "workload": {"repetitions": 1},
             "execution": {"max_active_episodes": 1, "max_inflight_llm_requests": 1}}
    sweep = yaml.safe_load((configs_dir / "sweep.yaml").read_text(encoding="utf-8"))
    sweep["base"] = "lightning.pinned.yaml"
    return {"lightning.pinned.yaml": lightning, "smoke.pinned.yaml": smoke, "sweep.pinned.yaml": sweep}


HEADER = "# Generated by `rollout-cost pin` for one GPU session. Commit it with the session's results.\n"


def write_pinned(configs_dir: Path, **kwargs) -> list[Path]:
    written = []
    for name, data in pinned_configs(configs_dir, **kwargs).items():
        path = configs_dir / name
        path.write_text(HEADER + yaml.safe_dump(data, sort_keys=False), encoding="utf-8", newline="\n")
        written.append(path)
    return written
